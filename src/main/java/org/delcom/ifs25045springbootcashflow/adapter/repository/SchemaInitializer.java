package org.delcom.ifs25045springbootcashflow.adapter.repository;

import org.delcom.ifs25045springbootcashflow.domain.exception.RepositoryException;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import javax.sql.DataSource;

/** Membuat tabel users dan transactions bila belum ada (idempotent). */
public class SchemaInitializer {
    static final String CREATE_USERS = """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(50) NOT NULL UNIQUE,
                name VARCHAR(100) NOT NULL,
                password_hash VARCHAR(64) NOT NULL,
                role VARCHAR(20) NOT NULL,
                photo_path VARCHAR(500),
                created_at TIMESTAMP NOT NULL
            )""";

    static final String CREATE_TRANSACTIONS = """
            CREATE TABLE IF NOT EXISTS transactions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                description TEXT NOT NULL,
                amount BIGINT NOT NULL,
                type VARCHAR(20) NOT NULL,
                proof_path VARCHAR(500),
                created_at TIMESTAMP NOT NULL,
                CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
            )""";

    static final String CREATE_INDEX =
            "CREATE INDEX IF NOT EXISTS idx_transactions_user_id ON transactions(user_id)";

    private final DataSource dataSource;

    public SchemaInitializer(DataSource dataSource) {
        this.dataSource = dataSource;
    }

    public void initialize() {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute(CREATE_USERS);
            statement.execute(CREATE_TRANSACTIONS);
            statement.execute(CREATE_INDEX);
        } catch (SQLException e) {
            throw new RepositoryException("Gagal menginisialisasi skema database", e);
        }
    }
}
